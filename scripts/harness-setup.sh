#!/bin/bash
# harness-setup.sh - create (or repair) the .harness/ scaffold in the current project.
#
# Safe to re-run: it MERGES (adds what is missing, refreshes wrappers) and never
# overwrites your config, mcp.json, progress log or feature list unless --force.
#
# Usage: harness-setup.sh [options]
#   --preset P              web     = coder -> tester with the Playwright MCP (browser testing)
#                           cli     = coder -> tester, no browser (also: api, data, docs - same pipeline,
#                                     different guidance for the initializer and tester)
#                           library = coder only; the verify gate (tests) is the verifier
#                           none    = coder only (claims are accepted after the verify gate)
#                           every preset except none also runs the curator every 10 sessions
#                           default: web if package.json/index.html exists, else cli
#   --max-sessions N        session cap written to config.json (default 100)
#   --no-browser            same as --preset cli when the preset would be web
#   --force                 overwrite config.json, mcp.json, progress.md and reset runner state
#   --check                 only check prerequisites and report; change nothing
#   --for-init              (used by harness-init) refuse if a feature list already exists, unless --force;
#                           also refuses when the git tree has uncommitted changes, unless --allow-dirty
#   --allow-dirty           let harness commits include your existing uncommitted changes
#   --branch NAME           create/switch to branch NAME before initializing (keeps your main branch untouched)
#   --refresh               only rewrite the .harness/*.sh wrappers (after a plugin update/move), then exit
#   --trust                 record the current risky config as trusted (see "trust" in the README), then exit
#   --finalize              after the initializer ran: validate + lock the feature list + first commit
#   --notify                add desktop-notification hooks (needs_human, run_ended) to config.json, then exit

set -euo pipefail

PLUGIN_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HARNESS_DIR="${HARNESS_DIR:-.harness}"
export HARNESS_DIR
# shellcheck source=harness-ignores.sh
source "$PLUGIN_ROOT/scripts/harness-ignores.sh"

PRESET=""; MAX_SESSIONS=""; FORCE=0; CHECK=0; FOR_INIT=0; FINALIZE=0; NO_BROWSER=0; ALLOW_DIRTY=0; BRANCH=""; REFRESH=0; TRUST=0; NOTIFY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --preset)       PRESET="${2:?web|cli|none}"; shift 2 ;;
    --max-sessions) MAX_SESSIONS="${2:?number required}"; shift 2 ;;
    --no-browser)   NO_BROWSER=1; shift ;;
    --force)        FORCE=1; shift ;;
    --check)        CHECK=1; shift ;;
    --for-init)     FOR_INIT=1; shift ;;
    --finalize)     FINALIZE=1; shift ;;
    --allow-dirty)  ALLOW_DIRTY=1; shift ;;
    --branch)       BRANCH="${2:?branch name required}"; shift 2 ;;
    --refresh)      REFRESH=1; shift ;;
    --trust)        TRUST=1; shift ;;
    --notify)       NOTIFY=1; shift ;;
    -h|--help)      sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done
case "$PRESET" in ""|web|cli|api|library|data|docs|none) ;; *) echo "❌ --preset must be web, cli, api, library, data, docs or none" >&2; exit 1 ;; esac
[[ "$MAX_SESSIONS" =~ ^([0-9]+)?$ ]] || { echo "❌ --max-sessions must be a number" >&2; exit 1; }

# Wrappers so agents and users never need to know the plugin path. They resolve the plugin at run
# time ($CLAUDE_PLUGIN_ROOT, then the path recorded here, then the newest installed copy) so a plugin
# update or move does not break them; /harness-run also refreshes them on every start.
refresh_wrappers() {
  mkdir -p "$HARNESS_DIR"
  local pair name target
  for pair in "feature-list.sh:feature-list.sh" "step.sh:harness-step.sh" "run.sh:harness-run.sh" "status.sh:harness-status.sh" "backlog.sh:backlog.sh" "doctor.sh:harness-doctor.sh" "notify.sh:notify.sh" "trigger.sh:harness-trigger.sh" "intake.sh:harness-intake.sh" "replay.sh:harness-replay.sh"; do
    name="${pair%%:*}"; target="${pair##*:}"
    cat > "$HARNESS_DIR/$name" <<WRAP
#!/bin/bash
# generated by wreck-it-ralph harness-setup (refresh with: /wreck-it-ralph:setup --refresh)
T="$target"
for P in "\${CLAUDE_PLUGIN_ROOT:-}" "$PLUGIN_ROOT"; do
  [[ -n "\$P" && -x "\$P/scripts/\$T" ]] && exec "\$P/scripts/\$T" "\$@"
done
P="\$(ls -d "\$HOME"/.claude/plugins/cache/*/wreck-it-ralph/*/scripts/"\$T" "\$HOME"/.claude/plugins/cache/*/wreck-it-ralph-loop/*/scripts/"\$T" 2>/dev/null | sort -V | tail -n1)"
[[ -n "\$P" && -x "\$P" ]] && exec "\$P" "\$@"
echo "wreck-it-ralph: plugin scripts not found (recorded: $PLUGIN_ROOT). Run /wreck-it-ralph:setup --refresh" >&2
exit 127
WRAP
    chmod +x "$HARNESS_DIR/$name"
  done
}

if [[ $REFRESH -eq 1 ]]; then
  refresh_wrappers; echo "refreshed $HARNESS_DIR wrappers -> $PLUGIN_ROOT"; exit 0
fi
if [[ $NOTIFY -eq 1 ]]; then
  [[ -f "$HARNESS_DIR/config.json" ]] || { echo "❌ $HARNESS_DIR/config.json missing: run setup first" >&2; exit 1; }
  WAS_TRUSTED=0; "$PLUGIN_ROOT/scripts/harness-step.sh" trust status >/dev/null 2>&1 && WAS_TRUSTED=1
  jq '.hooks = ((.hooks // {}) as $h | $h
        + {needs_human: ((($h.needs_human // []) | if type == "string" then [.] else . end) + ["cmd:.harness/notify.sh"] | unique),
           run_ended:   ((($h.run_ended   // []) | if type == "string" then [.] else . end) + ["cmd:.harness/notify.sh"] | unique)})' \
    "$HARNESS_DIR/config.json" > "$HARNESS_DIR/c.tmp.$$" && mv "$HARNESS_DIR/c.tmp.$$" "$HARNESS_DIR/config.json"
  refresh_wrappers
  # Our own, requested change: keep trust if the config was trusted before it.
  if [[ $WAS_TRUSTED -eq 1 ]]; then "$PLUGIN_ROOT/scripts/harness-step.sh" trust accept >/dev/null; fi
  echo "✅ notification hooks added (needs_human, run_ended -> .harness/notify.sh)"
  [[ $WAS_TRUSTED -eq 1 ]] || echo "   ⚠ review the config with /wreck-it-ralph:trust before the next run"
  exit 0
fi
if [[ $TRUST -eq 1 ]]; then
  "$PLUGIN_ROOT/scripts/harness-step.sh" trust accept; exit 0
fi

if [[ $FINALIZE -eq 1 ]]; then
  "$PLUGIN_ROOT/scripts/feature-list.sh" validate
  [[ -x "$HARNESS_DIR/init.sh" ]] || { echo "❌ $HARNESS_DIR/init.sh missing or not executable" >&2; exit 1; }
  "$PLUGIN_ROOT/scripts/feature-list.sh" lock
  # The initializer ran in the user's own session; its verify commands are trusted along with the
  # config we generated (an untrusted cloned config still has to go through /wreck-it-ralph:trust).
  if "$PLUGIN_ROOT/scripts/harness-step.sh" trust accept-verify >/dev/null 2>&1; then
    V="$("$PLUGIN_ROOT/scripts/feature-list.sh" verify-cmds | sort -u)"
    [[ -n "$V" ]] && { echo "Feature verify commands (run by the gate before the tester):"; printf '%s\n' "$V" | sed 's/^/  $ /'; }
  fi
  [[ -f "$HARNESS_DIR/proposals.json" ]] || echo '{"proposals":[]}' > "$HARNESS_DIR/proposals.json"
  ensure_all_ignores "$HARNESS_DIR"
  git add -A
  if ! git diff --cached --quiet; then
    git commit -qm "harness: initial environment (feature list, init.sh, progress log)" \
      || { echo "❌ git commit failed (is git user.name/user.email set?)" >&2; exit 1; }
  fi
  echo "✅ Harness finalized. Start the loop with /wreck-it-ralph:run (or $HARNESS_DIR/run.sh for headless runs)."
  exit 0
fi

# ---------- prerequisites ----------
MISSING=0
need() { # tool, required(1/0), hint
  if command -v "$1" >/dev/null 2>&1; then echo "  ✓ $1"
  elif [[ "$2" == "1" ]]; then echo "  ✗ $1 (required) - $3"; MISSING=1
  else echo "  ! $1 not found - $3"; fi
}
echo "Prerequisites:"
need git 1 "install git"
need jq 1 "brew install jq / apt install jq"
if [[ -n "$(git config user.email 2>/dev/null)" && -n "$(git config user.name 2>/dev/null)" ]] || [[ -n "${GIT_AUTHOR_EMAIL:-}" && -n "${GIT_AUTHOR_NAME:-}" ]]; then
  echo "  ✓ git identity"
else
  echo "  ✗ git identity (required) - git config user.name \"Your Name\" && git config user.email you@example.com"; MISSING=1
fi
need claude 0 "needed only for headless runs (.harness/run.sh)"
need npx 0 "needed for the Playwright MCP (browser testing); install Node.js"
if [[ $CHECK -eq 1 ]]; then
  [[ $MISSING -eq 0 ]] && echo "✅ all required tools present" || echo "❌ install the missing tools above"
  exit $MISSING
fi
[[ $MISSING -eq 0 ]] || { echo "❌ install the required tools above and re-run" >&2; exit 1; }

if [[ $FOR_INIT -eq 1 && -f "$HARNESS_DIR/feature_list.json" && $FORCE -eq 0 ]]; then
  echo "❌ $HARNESS_DIR is already initialized (feature_list.json exists). Use --force to re-initialize." >&2
  exit 1
fi

# ---------- existing work safety (the harness commits with `git add -A`) ----------
HAS_HEAD=0; git rev-parse --verify -q HEAD >/dev/null 2>&1 && HAS_HEAD=1
if [[ $FOR_INIT -eq 1 && $HAS_HEAD -eq 1 && $ALLOW_DIRTY -eq 0 ]]; then
  DIRTY="$(git status --porcelain --untracked-files=all -- . ':!.harness' ':!.gitignore' 2>/dev/null | head -n 8 || true)"
  if [[ -n "$DIRTY" ]]; then
    echo "❌ You have uncommitted changes; the harness would commit them along with its own work:" >&2
    echo "$DIRTY" | sed 's/^/     /' >&2
    echo "   Commit or stash them first, or re-run with --allow-dirty (or --branch NAME to work on a separate branch)." >&2
    exit 1
  fi
fi
if [[ $FOR_INIT -eq 1 && $HAS_HEAD -eq 0 ]] && [[ -n "$(ls -A . 2>/dev/null | grep -v '^\.harness$' | grep -v '^\.git$' | head -n1)" ]]; then
  echo "  note: repository has no commits yet; the first harness commit will include all existing files here."
fi
if [[ -n "$BRANCH" ]]; then
  if [[ $HAS_HEAD -eq 1 ]]; then
    git checkout -q -B "$BRANCH" && echo "  working on branch: $BRANCH"
  else
    git rev-parse --git-dir >/dev/null 2>&1 || git init -q
    git checkout -q -b "$BRANCH" 2>/dev/null || true
    echo "  working on branch: $BRANCH (will exist after the first commit)"
  fi
fi

# ---------- preset ----------
if [[ -z "$PRESET" ]]; then
  if [[ -f package.json || -f index.html ]]; then PRESET=web; else PRESET=cli; fi
fi
if [[ $NO_BROWSER -eq 1 && "$PRESET" == web ]]; then PRESET=cli; fi

# ---------- layout ----------
CREATED=(); KEPT=()
mkdir -p "$HARNESS_DIR/agents" "$HARNESS_DIR/sessions"

if [[ ! -f "$HARNESS_DIR/config.json" || $FORCE -eq 1 ]]; then
  jq --arg preset "$PRESET" --argjson max "${MAX_SESSIONS:-100}" '
    .max_sessions = $max | .preset = $preset
    | if $preset == "web" then .mcp_config = ".harness/mcp.json" else .mcp_config = "" end
    | if $preset == "none" then .pipeline = [{agent: "coder", blocking: true}]
      elif $preset == "library" then .pipeline = [.pipeline[] | select(.agent != "tester")]
      else . end
  ' "$PLUGIN_ROOT/templates/config.json" > "$HARNESS_DIR/config.json"
  CREATED+=("config.json (preset: $PRESET)")
else
  KEPT+=("config.json")
  if [[ -n "$MAX_SESSIONS" ]]; then
    jq --argjson max "$MAX_SESSIONS" '.max_sessions = $max' "$HARNESS_DIR/config.json" > "$HARNESS_DIR/c.tmp.$$" \
      && mv "$HARNESS_DIR/c.tmp.$$" "$HARNESS_DIR/config.json"
    echo "  updated max_sessions = $MAX_SESSIONS"
  fi
fi

if [[ "$PRESET" == web ]]; then
  if [[ ! -f "$HARNESS_DIR/mcp.json" || $FORCE -eq 1 ]]; then
    cp "$PLUGIN_ROOT/templates/mcp.json" "$HARNESS_DIR/mcp.json"; CREATED+=("mcp.json (Playwright)")
  else KEPT+=("mcp.json"); fi
fi

if [[ ! -f "$HARNESS_DIR/learnings.md" || $FORCE -eq 1 ]]; then
  printf '# Learnings\n\n(distilled by the curator agent; every session reads this first. Keep it short and true.)\n' > "$HARNESS_DIR/learnings.md"; CREATED+=("learnings.md")
fi
if [[ ! -f "$HARNESS_DIR/progress.md" || $FORCE -eq 1 ]]; then
  printf '# Progress log\n\n(append-only; one entry per session)\n' > "$HARNESS_DIR/progress.md"; CREATED+=("progress.md")
else KEPT+=("progress.md"); fi

if [[ $FORCE -eq 1 ]]; then
  rm -f "$HARNESS_DIR/STOP" "$HARNESS_DIR/.feature_list.lock.json" "$HARNESS_DIR/session_count" \
        "$HARNESS_DIR/last-run.md" "$HARNESS_DIR/runner.pid" "$HARNESS_DIR/.step_state.json"
fi
# Logs from earlier (possibly failed) attempts are only worth keeping when resuming.
if [[ $FOR_INIT -eq 1 || $FORCE -eq 1 ]]; then find "$HARNESS_DIR/sessions" -type f -delete 2>/dev/null || true; fi

refresh_wrappers
CREATED+=("wrappers: feature-list.sh step.sh run.sh status.sh backlog.sh doctor.sh notify.sh trigger.sh intake.sh")

if [[ ! -f "$HARNESS_DIR/README.md" ]]; then
  cat > "$HARNESS_DIR/README.md" <<'EOF'
# .harness

State for the wreck-it-ralph long-running agent harness. Agents work in fresh contexts; everything they need is here and in git.

- `feature_list.json`  source of truth; agents only change statuses via `./feature-list.sh claim|pass|fail|ask`
- `proposals.json`     backlog changes (add / amend / drop features) awaiting human approval (`./backlog.sh`)
- `learnings.md`       distilled lessons (curator); read this first
- `progress.md`        append-only session log (older entries rotate into `progress/`)
- `init.sh`            starts the app + smoke test, run at the start of every session
- `config.json`        pipeline, limits, permission mode (headless), final verification
- `mcp.json`           browser (Playwright) MCP config, web preset only
- `agents/`            optional custom agents (see the plugin's templates/agents)
- `step.sh`, `run.sh`, `status.sh`, `backlog.sh`  gates, headless runner, status, proposals (wrappers into the plugin)

Stop a running loop: `touch .harness/STOP`.
EOF
  CREATED+=("README.md")
fi

ensure_all_ignores "$HARNESS_DIR"

if ! git rev-parse --git-dir >/dev/null 2>&1; then git init -q; CREATED+=("git repository"); fi

# Config files we just generated from the plugin's own templates are trusted automatically;
# a config that already existed (e.g. from a cloned repo) must be reviewed with /harness-trust.
if [[ " ${CREATED[*]} " == *" config.json"* ]]; then
  "$PLUGIN_ROOT/scripts/harness-step.sh" trust accept >/dev/null && CREATED+=("trust recorded for generated config")
else
  "$PLUGIN_ROOT/scripts/harness-step.sh" trust status >/dev/null 2>&1 || echo "   ⚠ existing config is not trusted yet: review it with /wreck-it-ralph:trust before running a loop"
fi

echo
echo "✅ Harness scaffold ready in $HARNESS_DIR/ (preset: $PRESET)"
for c in "${CREATED[@]}"; do echo "   + $c"; done
if [[ ${#KEPT[@]} -gt 0 ]]; then echo "   = kept existing: ${KEPT[*]}"; fi
if [[ "$PRESET" == web ]] && ! command -v npx >/dev/null 2>&1; then echo "   ⚠ web preset needs npx for the Playwright MCP"; fi
echo "   Next: /wreck-it-ralph:init \"<goal>\"  (the initializer writes feature_list.json, init.sh, progress.md)"
